def rw(name, fn):
    p = os.path.join(ROOT, name)
    s = io.open(p, encoding="utf-8").read()
    s2 = fn(s)
    if s2 != s:
        io.open(p, "w", encoding="utf-8", newline="\n").write(s2)
        print("обновлён:", name)
    else:
        print("без изменений:", name)

